# various set methods 

# add()
def add_element(s, element):
    return s.add(element)

# clear()
def clear_element(s):
    return s.clear()

# discard():
def discard_element(s, element):
    return s.discard(element)

# remove(): 
def remove_element(s, element):
    return s.remove(element)

# pop(): 
def pop_element(s):
    return s.pop()

# len():
def length(s):
    return len(s)

# sorted(): 
def sort_set(a):
    return sorted(a)

# sum():
def sum_setValues(a):
    return sum(a)

# union():
def union_element(a, b):
    return a.union(b)

# difference():
def diff(a, b):
    return a.difference(b)

# intersection():
def common_in_set(a, b):
    return a.intersection(b)